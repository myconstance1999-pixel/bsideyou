    # bsideyou 使用指南

    ## 1. bsideyou 是什么
    一个本地运行的原生 macOS 菜单栏应用：把你合法持有的 BSide Offline 官方资源（HEVC 动态壁纸视频与环境音）
    播放在桌面上。非官方、与米哈游无关、完全在本机运行。

    ## 2. 第一次使用
    1. 启动 bsideyou，屏幕右上角菜单栏出现菜单栏图标。
    2. 首次使用会弹出引导：选择官方安装目录、具体版本或 assets 文件夹，授权访问画面与环境音。
       若发现多个可用版本，请选择其中一个具体版本文件夹。
    3. 验证通过后林离会出现在桌面，以后每次启动自动恢复。

    ## 3. 日常控制
    点击菜单栏图标打开控制中心：这里显示当前状态、林离与主要入口。
    - **暂停 / 恢复**：控制中心的醒目按钮。
    - **主音量**：整体音量。
    - **日常…**：查看当前背景、当前时段和活动入口，也可以预览并更换背景；浏览不会自动播放或更改设置。
    - **演奏曲库**：点歌演奏。
    - **设置…**：画面（当前背景与时段）、声音（主音量、环境音、
      音乐）、使用场景以及资源、记录与高级选项都在这里。
      使用场景提供日常陪伴、轻声背景（30%）、专注工作（15%）、无声画面和暂停陪伴，
      每项都有适用情境和声音／暂停说明；百分比相对于当前音量设置。
    - **底部播放条**：显示当前曲目、播放方式（顺序播放／随机播放／列表循环／单曲循环）和“即将播放”队列入口。

    ## 4. 音频
    - **主音量**：整体音量。
    - **环境音**：来自官方资源 `Wallpaper_Ambience` 的环境音/钢琴循环——你现在听到的就是它。
    - **音乐**：演奏视频的音轨音量；日常壁纸视频本身没有音轨。
    - **点歌演奏**：点击控制中心的“演奏曲库”，选择自己的官方音乐总目录、分类或单曲文件夹。
      搜索或按分类／来源筛选后，双击一首或点“播放”会从这首开始，按当前显示顺序继续播放；
      “只播放这首”只播一首，“下一首播放”插到当前歌曲之后，“稍后播放”只加入队列末尾。
      不支持的机位或缺失版本会明确提示。
      点播时会确认所选文件可用，随后完整播放。演奏期间日常视频和环境音停止，避免叠播。
      暂停演奏不改写日常偏好；停止或自然结束后返回当前北京时间（或当前固定时段）的日常。
      若全局已暂停、选择了“暂停陪伴”或系统抑制，恢复演奏按钮不会越过这些限制。

    ## 5. 自动时间
    “自动”始终使用北京时间：06:00–17:30 白天、17:30–20:00 傍晚、其余时间夜晚。
    Mac 的系统时区不影响这个排程；睡醒后直接按当前北京时间重新选择时段。
    这是本应用自定义的排程，不是考证出的官方原始时间规则。想固定某个时段就取消“自动”。
    在设置 → 画面中可固定时段；具体背景在“日常”页预览并更换。

    ## 6. 桌面 / 预览
    - **桌面壁纸模式**：画面在桌面图标层之下，Finder 图标仍可点击，不抢焦点。
    - **浮窗预览模式**：一个普通悬浮小窗，用于桌面模式不可用时查看画面。

    ## 7. 登录时启动
    设置 → 通用 → “登录时启动 bsideyou”。开关反映的是系统真实状态；
    如显示“待批准”，请到 系统设置 → 通用 → 登录项 中批准。

    ## 8. 休眠 / 全屏
    以下情况会自动处理，恢复正常后自动恢复原状：
    - **系统睡眠、屏幕关闭或锁定**：暂停播放。
    - **前台有全屏应用**：默认暂停画面并静音（可在设置中调整）。
    - **系统过热**：重度过热时暂停播放；一般过热时自动降低音量。
    - **低电量模式**：自动把音量减半。

    ## 9. 故障排查
    - **桌面没有林离**：打开诊断查看状态；必要时到 设置 → 高级 → “重启壁纸服务”。
    - **资源路径失效**（移动/删除了目录）：设置 → 内容 → 更改… 重新选择。
    - **没有声音**：日常请检查环境音；演奏请检查音乐、主音量、静音与模式。另需检查系统音量。
    - **演奏素材不匹配或路径失效**：曲库 → 管理音乐 → “音乐文件夹…” 重新绑定；“刷新曲库”重新检查候选。
      只使用身份可确认的文件；改名视频或编码未知的版本不会自动冒充其他时段或机位。
    - **服务重启时演奏停止**：会话随播放器退出而结束；日常会自动恢复，需要时重新点播。
    - **如何打开诊断**：菜单栏图标 → 控制中心 → “设置…” → 高级 → “打开诊断…”。
      “复制诊断信息”可一键复制当前状态用于反馈。

    ## 10. 数据位置
    - 偏好设置：`~/Library/Application Support/BSideMac/preferences.json`
    - 日志：同目录下 `control.log`（控制链路）与 `agent.log`（播放进程）
    官方资源目录只被读取，永不写入。

    ## 11. 隐私
    官方资源仅本地读取；不上传任何内容；无遥测；无 AI 联网功能。
    """
}
